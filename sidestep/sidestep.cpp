static std::string norm_ws(const char *s) {
  std::string r;
  while (*s) {
    if (*s == '\'' || *s == '"') {
      char q = *s;
      r += *s++;
      while (*s && *s != q) {
        if (*s == '\\' && s[1]) { r += *s++; }  
        r += *s++;
      }
      if (*s) r += *s++;
    } else if (*s == ' ' || *s == '\n' || *s == '\r' || *s == '\t') {
      s++;
    } else {
      r += *s++;
    }
  }
  
  while (r.size() >= 2 && r[0] == '(' && r[r.size()-1] == ')') {
    int d = 0;
    bool spans = true;
    for (size_t i = 0; i < r.size() - 1; i++) {
      if (r[i] == '(') d++;
      else if (r[i] == ')') d--;
      if (d == 0) { spans = false; break; }
    }
    if (!spans) break;
    r = r.substr(1, r.size() - 2);
  }
  return r;
}



static std::string norm_vars(const std::string &s) {
  std::string r;
  std::map<std::string, std::string> vmap;
  int next_id = 0;
  for (size_t i = 0; i < s.size(); ) {
    



    if (s[i] == '\'' || s[i] == '"') {
      char q = s[i];
      r += s[i++];
      while (i < s.size() && s[i] != q) { r += s[i++]; }
      if (i < s.size()) r += s[i++];
      continue;
    }
    if (s[i] >= 'A' && s[i] <= 'Z') {
      size_t vs = i;
      while (i < s.size() && (isalnum(s[i]) || s[i] == '_')) i++;
      std::string var = s.substr(vs, i - vs);
      
      if (i < s.size() && s[i] == '(') {
        r += var;
        continue;
      }
      auto it = vmap.find(var);
      if (it == vmap.end()) {
        char buf[16];
        snprintf(buf, sizeof(buf), "V%d", next_id++);
        vmap[var] = buf;
        r += buf;
      } else {
        r += it->second;
      }
    } else {
      r += s[i++];
    }
  }
  return r;
}

int sidestep_verify(const char *rule,
                    const char **parents, int nparents,
                    const char *conclusion,
                    const char *lang) {
  

  ss_init_crash_log();
  ss_current_op = "verify";
  ss_current_rule = rule ? rule : "?";
  

  if (nparents >= 1) {
    


    if (strcmp(rule, "split_conjunct") == 0) {
      std::string concl_norm = norm_ws(conclusion);
      std::string par_norm = norm_ws(parents[0]);
      










      bool pure_conj = true;
      {
        int d0 = 0;
        for (size_t i = 0; i < par_norm.size() && pure_conj; i++) {
          char c = par_norm[i];
          if (c == '\'' || c == '"') {
            char q = c;
            for (i++; i < par_norm.size() && par_norm[i] != q; i++) {}
          } else if (c == '(' || c == '[') d0++;
          else if (c == ')' || c == ']') d0--;
          else if (d0 == 0 && (c == '|' || c == '<' || c == '>'))
            pure_conj = false;
        }
      }
      

      auto split_conjuncts = [](const std::string &s) {
        std::vector<std::string> parts;
        int depth = 0;
        size_t start = 0;
        for (size_t i = 0; i <= s.size(); i++) {
          char c = (i < s.size()) ? s[i] : '&';
          if (c == '(' || c == '[') depth++;
          else if (c == ')' || c == ']') depth--;
          else if (c == '&' && depth == 0) {
            std::string part = s.substr(start, i - start);
            
            size_t a = 0, b = part.size();
            while (a < b && part[a] == ' ') a++;
            while (b > a && part[b-1] == ' ') b--;
            if (a < b) {
              part = part.substr(a, b - a);
              
              while (part.size() >= 2 && part[0] == '(' &&
                     part[part.size()-1] == ')') {
                int d2 = 0;
                bool spans = true;
                for (size_t j = 0; j < part.size() - 1; j++) {
                  if (part[j] == '(') d2++;
                  else if (part[j] == ')') d2--;
                  if (d2 == 0) { spans = false; break; }
                }
                if (!spans) break;
                part = part.substr(1, part.size() - 2);
              }
              parts.push_back(part);
            }
            start = i + 1;
          }
        }
        return parts;
      };
      if (pure_conj) {
        auto conjuncts = split_conjuncts(par_norm);
        for (size_t i = 0; i < conjuncts.size(); i++)
          if (conjuncts[i] == concl_norm) return 1;
        
        std::string concl_vn = norm_vars(concl_norm);
        std::string par_vn = norm_vars(par_norm);
        conjuncts = split_conjuncts(par_vn);
        for (size_t i = 0; i < conjuncts.size(); i++)
          if (conjuncts[i] == concl_vn) return 1;
      }
    }
    





    if (strcmp(rule, "cn") == 0 && nparents == 1) {
      std::string concl_norm = norm_ws(conclusion);
      std::string par_norm = norm_ws(parents[0]);
      if (par_norm == concl_norm)
        return 1;
      
      auto split_lits = [](const std::string &s) {
        std::vector<std::string> lits;
        int depth = 0;
        size_t start = 0;
        for (size_t i = 0; i <= s.size(); i++) {
          char c = (i < s.size()) ? s[i] : '|';
          if (c == '(' || c == '[') depth++;
          else if (c == ')' || c == ']') depth--;
          else if (c == '|' && depth == 0) {
            std::string lit = s.substr(start, i - start);
            
            size_t a = 0, b = lit.size();
            while (a < b && lit[a] == ' ') a++;
            while (b > a && lit[b-1] == ' ') b--;
            if (a < b) lits.push_back(lit.substr(a, b - a));
            start = i + 1;
          }
        }
        return lits;
      };
      auto concl_lits = split_lits(concl_norm);
      auto par_lits = split_lits(par_norm);
      bool all_found = true;
      for (size_t i = 0; i < concl_lits.size() && all_found; i++) {
        bool found = false;
        for (size_t j = 0; j < par_lits.size(); j++) {
          if (concl_lits[i] == par_lits[j]) { found = true; break; }
        }
        if (!found) all_found = false;
      }
      
      if (all_found && !concl_lits.empty()) {
        bool removals_ok = true;
        for (size_t i = 0; i < par_lits.size() && removals_ok; i++) {
          bool in_concl = false;
          for (size_t j = 0; j < concl_lits.size(); j++)
            if (par_lits[i] == concl_lits[j]) { in_concl = true; break; }
          if (!in_concl) {
            
            bool is_dup = false;
            for (size_t j = 0; j < i; j++)
              if (par_lits[i] == par_lits[j]) { is_dup = true; break; }
            if (!is_dup) removals_ok = false;
          }
        }
        if (removals_ok) return 1;
      }
      
    }
    
    if (strcmp(rule, "copy") == 0 && nparents == 1) {
      std::string concl_norm = norm_ws(conclusion);
      std::string par_norm = norm_ws(parents[0]);
      if (par_norm == concl_norm)
        return 1;
    }
  }

  
  if (lang && strcmp(lang, "cnf") != 0)
    return -1;

  sidestep::TermPool pool;
  sidestep::SymbolTable syms;

  




  bool concl_clean = true;
  sidestep::Clause concl = sidestep::parse_clause(conclusion, pool, syms,
                                                   &concl_clean);
  if (!concl_clean) return -1;

  
  if (concl.lits.size() == 1) {
    const std::string &name = syms.name(concl.lits[0].sym);
    if (name == "$false" || name == "false")
      concl.lits.clear();
  }

  


  std::vector<sidestep::Clause> parent_clauses;
  for (int i = 0; i < nparents; i++) {
    bool cl_clean = true;
    sidestep::Clause cl = sidestep::parse_clause(parents[i], pool, syms,
                                                  &cl_clean);
    if (!cl_clean) return -1;
    if (cl.lits.size() == 1) {
      const std::string &name = syms.name(cl.lits[0].sym);
      if (name == "$false" || name == "false")
        cl.lits.clear();
    }
    parent_clauses.push_back(cl);
  }

  



  ss_install_handlers_once();

  int rc = -1;
  ss_guard_active = 1;
  if (sigsetjmp(ss_jmpbuf, 1) == 0) {
    struct timeval tv_start;
    gettimeofday(&tv_start, NULL);
    sidestep::deadline_start = tv_start;
    sidestep::op_count = 0;
    














    {
      const char *e = getenv("SIDESTEP_OP_LIMIT");
      sidestep::op_limit = (e && *e) ? atoi(e) : 5000;
    }
    sidestep::deadline_sticky = false;
    sidestep::deadline_ms = 10;  

    


    if ((strcmp(rule, "skolemize") == 0 || strcmp(rule, "skolemisation") == 0 ||
         strcmp(rule, "skolemization") == 0 || strcmp(rule, "clausify") == 0) &&
        !parent_clauses.empty()) {
      rc = sidestep::verify_skolemize_clausify(
          parent_clauses[0], concl, pool, syms);
    } else {
      rc = sidestep::dispatch_rule(rule, parent_clauses, concl, pool, syms);
    }
  }
  

  ss_guard_active = 0;
  sidestep::deadline_ms = 0;
  sidestep::op_limit = 0;

  


  if (const char *tlog = getenv("SIDESTEP_TIMING_LOG")) {
    static int tlog_fd = -2;
    if (tlog_fd == -2) {
      tlog_fd = open(tlog, O_WRONLY | O_CREAT | O_APPEND, 0644);
    }
    if (tlog_fd >= 0) {
      struct timeval tv_end;
      gettimeofday(&tv_end, NULL);
      long us = (tv_end.tv_sec  - sidestep::deadline_start.tv_sec)  * 1000000L
              + (tv_end.tv_usec - sidestep::deadline_start.tv_usec);
      char buf[256];
      int n = snprintf(buf, sizeof(buf), "%s\t%d\t%ld\t%d\t%s\n",
                       rule ? rule : "?", rc, us,
                       sidestep::op_count,
                       ss_current_ctx ? ss_current_ctx : "");
      if (n > 0) (void)!write(tlog_fd, buf, n);
    }
  }

  return rc;
}






int sidestep_compute(const char *rule,
                     const char **parents, int nparents,
                     const char *lang,
                     char ***out_bodies,
                     int max_candidates) {
  if (out_bodies) *out_bodies = NULL;
  if (lang && strcmp(lang, "cnf") != 0) return -1;
  if (nparents < 1 || max_candidates <= 0) return -1;

  
  ss_init_crash_log();
  ss_current_op = "compute";
  ss_current_rule = rule ? rule : "?";

  sidestep::TermPool pool;
  sidestep::SymbolTable syms;

  std::vector<sidestep::Clause> parent_clauses;
  for (int i = 0; i < nparents; i++) {
    bool cl_clean = true;
    sidestep::Clause cl = sidestep::parse_clause(parents[i], pool, syms,
                                                  &cl_clean);
    if (!cl_clean) return -1;
    if (cl.lits.size() == 1) {
      const std::string &name = syms.name(cl.lits[0].sym);
      if (name == "$false" || name == "false")
        cl.lits.clear();
    }
    parent_clauses.push_back(cl);
  }

  
  ss_install_handlers_once();

  std::vector<std::string> bodies;
  int rc = -1;
  ss_guard_active = 1;
  if (sigsetjmp(ss_jmpbuf, 1) == 0) {
    struct timeval tv_start;
    gettimeofday(&tv_start, NULL);
    sidestep::deadline_start = tv_start;
    sidestep::op_count = 0;
    {
      const char *e = getenv("SIDESTEP_OP_LIMIT");
      sidestep::op_limit = (e && *e) ? atoi(e) : 5000;
    }
    sidestep::deadline_sticky = false;
    sidestep::deadline_ms = 10;
    rc = sidestep::dispatch_compute(rule, parent_clauses, pool, syms,
                                    bodies, max_candidates);
  }
  

  ss_guard_active = 0;
  sidestep::deadline_ms = 0;
  sidestep::op_limit = 0;

  if (rc < 0) return -1;

  
  int n = (int)bodies.size();
  if (n == 0) { if (out_bodies) *out_bodies = NULL; return 0; }
  char **arr = (char **)malloc((size_t)n * sizeof(char *));
  if (!arr) return -1;
  for (int i = 0; i < n; i++) {
    arr[i] = strdup(bodies[i].c_str());
    if (!arr[i]) {
      for (int j = 0; j < i; j++) free(arr[j]);
      free(arr);
      return -1;
    }
  }
  if (out_bodies) *out_bodies = arr;
  return n;
}
