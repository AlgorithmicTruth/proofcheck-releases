static std::atomic<int> ss_handlers_installed{0};

static void ss_install_handlers_once(void) {
  int expected = 0;
  if (!ss_handlers_installed.compare_exchange_strong(expected, 1)) return;
  struct sigaction sa;
  memset(&sa, 0, sizeof(sa));
  sa.sa_handler = ss_crash_handler;
  sa.sa_flags = 0;
  sigaction(SIGSEGV, &sa, NULL);
  sigaction(SIGBUS,  &sa, NULL);
  




  sigaction(SIGALRM, &sa, NULL);
}

static void ss_init_crash_log(void) {
  if (ss_crash_log_fd != -2) return;
  const char *env = getenv("SIDESTEP_CRASH_LOG");
  char path_buf[1024];
  const char *path;
  if (env && *env) {
    path = env;
  } else {
    const char *tmp = getenv("TMPDIR");
    if (!tmp || !*tmp) tmp = "/tmp";
    int n = snprintf(path_buf, sizeof(path_buf),
                     "%s/sidestep_crashes.log", tmp);
    if (n <= 0 || n >= (int)sizeof(path_buf)) {
      ss_crash_log_fd = -1;
      return;
    }
    path = path_buf;
  }
  int fd = open(path, O_WRONLY | O_CREAT | O_APPEND, 0644);
  ss_crash_log_fd = (fd >= 0) ? fd : -1;
}


static int ss_itoa(unsigned long v, char *buf, int cap) {
  if (cap <= 0) return 0;
  char tmp[24];
  int n = 0;
  if (v == 0) tmp[n++] = '0';
  while (v > 0 && n < (int)sizeof(tmp)) { tmp[n++] = '0' + (v % 10); v /= 10; }
  int out = 0;
  while (n > 0 && out < cap) buf[out++] = tmp[--n];
  return out;
}

__attribute__((cold))
static void ss_crash_handler(int sig) {
  if (ss_guard_active) {
    const char *signame = (sig == SIGSEGV) ? "SIGSEGV"
                        : (sig == SIGBUS)  ? "SIGBUS"
                        : (sig == SIGALRM) ? "SIGALRM"
                        :                    "?";
    if (ss_crash_log_fd >= 0) {
      

      char buf[256];
      int n = 0;
      const char *p = "[sidestep pid=";
      while (*p && n < (int)sizeof(buf)) buf[n++] = *p++;
      n += ss_itoa((unsigned long)getpid(), buf + n, (int)sizeof(buf) - n);
      const char *p2 = "] caught ";
      while (*p2 && n < (int)sizeof(buf)) buf[n++] = *p2++;
      const char *p3 = signame;
      while (*p3 && n < (int)sizeof(buf)) buf[n++] = *p3++;
      const char *p4 = " in ";
      while (*p4 && n < (int)sizeof(buf)) buf[n++] = *p4++;
      const char *p5 = ss_current_op;
      while (*p5 && n < (int)sizeof(buf)) buf[n++] = *p5++;
      const char *p6 = "(rule=";
      while (*p6 && n < (int)sizeof(buf)) buf[n++] = *p6++;
      const char *p7 = ss_current_rule;
      while (*p7 && n < (int)sizeof(buf)) buf[n++] = *p7++;
      const char *p8 = ")";
      while (*p8 && n < (int)sizeof(buf)) buf[n++] = *p8++;
      
      if (ss_current_ctx && *ss_current_ctx) {
        const char *p9 = " ctx=";
        while (*p9 && n < (int)sizeof(buf)) buf[n++] = *p9++;
        const char *p10 = ss_current_ctx;
        while (*p10 && n < (int)sizeof(buf) - 1) buf[n++] = *p10++;
      }
      if (n < (int)sizeof(buf)) buf[n++] = '\n';
      write(ss_crash_log_fd, buf, n);
    }
    siglongjmp(ss_jmpbuf, 1);
  }
  
  signal(sig, SIG_DFL);
  raise(sig);
}

