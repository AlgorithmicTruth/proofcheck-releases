static int verify_instantiate(const Clause &parent, const Clause &concl,
                              TermPool &pool) {
  if (parent.lits.size() != concl.lits.size()) return -1;
  

  Subst sub;
  std::vector<bool> used(concl.lits.size(), false);
  for (size_t i = 0; i < parent.lits.size() && !deadline_expired(); i++) {
    bool found = false;
    for (size_t j = 0; j < concl.lits.size(); j++) {
      if (used[j]) continue;
      if (parent.lits[i].negated != concl.lits[j].negated) continue;
      if (parent.lits[i].sym != concl.lits[j].sym) continue;
      if (parent.lits[i].args.size() != concl.lits[j].args.size()) continue;
      Subst trial = sub;
      bool ok = true;
      for (size_t ai = 0; ai < parent.lits[i].args.size(); ai++) {
        if (!match(pool, parent.lits[i].args[ai],
                   concl.lits[j].args[ai], trial)) {
          ok = false; break;
        }
      }
      if (ok) { sub = trial; used[j] = true; found = true; break; }
    }
    if (!found) return -1;
  }
  return 1;
}






static int verify_consequence(const std::vector<Clause> &parents,
                              const Clause &concl, TermPool &pool,
                              const SymbolTable &syms) {
  





  for (size_t i = 0; i < parents.size(); i++) {
    if (clause_subset(concl, parents[i], pool) &&
        clause_subset(parents[i], concl, pool))
      return 1;
  }
  
  int rc = verify_sr(parents, concl, pool, syms);
  if (rc == 1) return 1;
  
  if (unlikely(deadline_expired())) return -1;
  rc = verify_rw(parents, concl, pool);
  if (rc == 1) return 1;
  
  if (unlikely(deadline_expired())) return -1;
  rc = verify_spm(parents, concl, pool, syms);
  if (rc == 1) return 1;
  return -1;
}




