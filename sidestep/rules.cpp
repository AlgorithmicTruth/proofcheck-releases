static int verify_binary_resolution(const std::vector<Clause> &parents,
                                     const Clause &concl,
                                     TermPool &pool,
                                     const SymbolTable &syms) {
  if (parents.size() < 2) return -1;
  



  SymbolTable &mut_syms = const_cast<SymbolTable &>(syms);
  for (size_t i = 0; i < parents.size() &&
       likely(!deadline_expired()); i++) {
    for (size_t j = 0; j < parents.size() &&
         likely(!deadline_expired()); j++) {
      if (i == j) continue;
      const Clause &p_i = parents[i];
      




      Clause p_j = clause_rename_vars(pool, mut_syms, parents[j]);
      for (size_t li = 0; li < p_i.lits.size() &&
           likely(!deadline_expired()); li++) {
        const Literal &Li = p_i.lits[li];
        for (size_t lj = 0; lj < p_j.lits.size() &&
             likely(!deadline_expired()); lj++) {
          const Literal &Lj = p_j.lits[lj];
          
          if (Li.sym != Lj.sym) continue;
          if (Li.negated == Lj.negated) continue;
          if (Li.args.size() != Lj.args.size()) continue;
          Subst sub;
          bool ok = true;
          for (size_t a = 0; a < Li.args.size(); a++) {
            if (!unify(pool, Li.args[a], Lj.args[a], sub)) { ok = false; break; }
          }
          if (!ok) continue;
          
          Clause result;
          for (size_t k = 0; k < p_i.lits.size(); k++) {
            if (k == li) continue;
            Literal nl = apply_subst_lit(pool, p_i.lits[k], sub);
            bool dup = false;
            for (size_t r = 0; r < result.lits.size(); r++) {
              if (lits_equal(result.lits[r], nl, pool)) { dup = true; break; }
            }
            if (!dup) result.lits.push_back(nl);
          }
          for (size_t k = 0; k < p_j.lits.size(); k++) {
            if (k == lj) continue;
            Literal nl = apply_subst_lit(pool, p_j.lits[k], sub);
            bool dup = false;
            for (size_t r = 0; r < result.lits.size(); r++) {
              if (lits_equal(result.lits[r], nl, pool)) { dup = true; break; }
            }
            if (!dup) result.lits.push_back(nl);
          }
          
          if (result.lits.size() == concl.lits.size() &&
              clause_subset(concl, result, pool) &&
              clause_subset(result, concl, pool))
            return 1;
          if (clauses_alpha_equal(result, concl, pool, syms))
            return 1;
        }
      }
    }
  }
  return -1;
}

static int verify_sr(const std::vector<Clause> &parents, const Clause &concl,
                     TermPool &pool, const SymbolTable &syms) {
  if (parents.size() < 2) return -1;

  





  for (size_t main_idx = 0; main_idx < parents.size() && likely(!deadline_expired()); main_idx++) {
    const Clause &main_cl = parents[main_idx];
    for (size_t li = 0; li < main_cl.lits.size() && likely(!deadline_expired()); li++) {
      for (size_t si = 0; si < parents.size() && likely(!deadline_expired()); si++) {
        if (si == main_idx) continue;
        const Clause &simp = parents[si];
        if (simp.lits.size() != 1) continue;
        Literal comp = simp.lits[0];
        comp.negated = !comp.negated;
        if (comp.sym != main_cl.lits[li].sym) continue;
        if (comp.negated != main_cl.lits[li].negated) continue;
        if (comp.args.size() != main_cl.lits[li].args.size()) continue;
        Subst sub;
        bool match_ok = true;
        for (size_t ai = 0; ai < comp.args.size(); ai++) {
          if (!unify(pool, comp.args[ai], main_cl.lits[li].args[ai], sub))
            { match_ok = false; break; }
        }
        if (!match_ok) continue;
        Clause result;
        for (size_t k = 0; k < main_cl.lits.size(); k++) {
          if (k == li) continue;
          result.lits.push_back(apply_subst_lit(pool, main_cl.lits[k], sub));
        }
        if (result.lits.size() == concl.lits.size() &&
            clause_subset(concl, result, pool) &&
            clause_subset(result, concl, pool))
          return 1;
        if (clauses_alpha_equal(result, concl, pool, syms))
          return 1;
      }
    }
  }

  



  for (size_t main_idx = 0; main_idx < parents.size() && likely(!deadline_expired()); main_idx++) {
    const Clause &main_cl = parents[main_idx];
    Clause result = main_cl;
    bool any_removed = false;
    for (size_t li = 0; li < result.lits.size() && likely(!deadline_expired()); ) {
      bool removed = false;
      for (size_t si = 0; si < parents.size() && likely(!deadline_expired()); si++) {
        if (si == main_idx) continue;
        const Clause &simp = parents[si];
        if (simp.lits.size() != 1) continue;
        Literal comp = simp.lits[0];
        comp.negated = !comp.negated;
        Subst sub;
        bool match_ok = false;
        if (comp.sym == result.lits[li].sym &&
            comp.negated == result.lits[li].negated &&
            comp.args.size() == result.lits[li].args.size()) {
          match_ok = true;
          for (size_t ai = 0; ai < comp.args.size(); ai++) {
            if (!unify(pool, comp.args[ai], result.lits[li].args[ai], sub))
              { match_ok = false; break; }
          }
        }
        if (match_ok) {
          result.lits.erase(result.lits.begin() + li);
          for (size_t k = 0; k < result.lits.size(); k++)
            result.lits[k] = apply_subst_lit(pool, result.lits[k], sub);
          removed = true;
          any_removed = true;
          break;
        }
      }
      if (!removed) li++;
    }
    if (!any_removed) continue;
    if (result.lits.size() == concl.lits.size() &&
        clause_subset(concl, result, pool) &&
        clause_subset(result, concl, pool))
      return 1;
    if (clauses_alpha_equal(result, concl, pool, syms))
      return 1;
  }
  return -1;
}





struct RwMatchData {
  TermPool *pool;
  int replacement;
  int lit_term;
  std::vector<std::vector<int>> found_positions;
  std::vector<Subst> found_substs;
};

static void rw_match_cb(const std::vector<int> &pos, const Subst &sub,
                        void *data) {
  RwMatchData *d = (RwMatchData *)data;
  d->found_positions.push_back(pos);
  d->found_substs.push_back(sub);
}



static std::vector<int> apply_one_rewrite(TermPool &pool, int term,
                                           int lhs, int rhs) {
  std::vector<int> results;
  RwMatchData data;
  data.pool = &pool;
  std::vector<int> pos_stack;
  find_matches(pool, term, lhs, pos_stack, rw_match_cb, &data);
  for (size_t mi = 0; mi < data.found_positions.size(); mi++) {
    int new_rhs = apply_subst(pool, rhs, data.found_substs[mi]);
    int result = replace_at(pool, term, data.found_positions[mi], 0, new_rhs);
    results.push_back(result);
  }
  return results;
}







struct RewriteResult {
  int term;
  Subst sub;
};
static std::vector<RewriteResult> apply_one_rewrite_subs(TermPool &pool, int term,
                                                          int lhs, int rhs) {
  std::vector<RewriteResult> results;
  RwMatchData data;
  data.pool = &pool;
  std::vector<int> pos_stack;
  find_matches(pool, term, lhs, pos_stack, rw_match_cb, &data);
  for (size_t mi = 0; mi < data.found_positions.size(); mi++) {
    int new_rhs = apply_subst(pool, rhs, data.found_substs[mi]);
    int new_term = replace_at(pool, term, data.found_positions[mi], 0, new_rhs);
    RewriteResult r;
    r.term = new_term;
    r.sub = data.found_substs[mi];
    results.push_back(r);
  }
  return results;
}


static bool clause_matches(const Clause &candidate, const Clause &concl,
                           const TermPool &pool) {
  return candidate.lits.size() == concl.lits.size() &&
         clause_subset(concl, candidate, pool) &&
         clause_subset(candidate, concl, pool);
}







static void canon_term_str(const TermPool &pool, const SymbolTable &syms,
                            int t, std::map<int, int> &var_map,
                            int &next_var, std::string &out,
                            int depth = 0) {
  if (unlikely(++op_count > op_limit || depth > 200)) return;
  const Term &term = pool.get(t);
  if (term.sym < 0) {
    std::map<int, int>::iterator it = var_map.find(term.sym);
    int id;
    if (it != var_map.end()) id = it->second;
    else { id = next_var++; var_map[term.sym] = id; }
    out += "V";
    char buf[16];
    snprintf(buf, sizeof(buf), "%d", id);
    out += buf;
    return;
  }
  out += syms.name(term.sym);
  if (!term.args.empty()) {
    out += "(";
    for (size_t i = 0; i < term.args.size(); i++) {
      if (i > 0) out += ",";
      canon_term_str(pool, syms, term.args[i], var_map, next_var, out, depth + 1);
    }
    out += ")";
  }
}

static std::string canon_lit_str(const TermPool &pool, const SymbolTable &syms,
                                  const Literal &lit,
                                  std::map<int, int> &var_map,
                                  int &next_var) {
  std::string s;
  if (lit.sym == EQ_SYM && lit.args.size() == 2) {
    

    std::map<int, int> vm_a = var_map; int nv_a = next_var;
    std::map<int, int> vm_b = var_map; int nv_b = next_var;
    std::string a, b;
    canon_term_str(pool, syms, lit.args[0], vm_a, nv_a, a);
    a += lit.negated ? "!=" : "=";
    canon_term_str(pool, syms, lit.args[1], vm_a, nv_a, a);
    canon_term_str(pool, syms, lit.args[1], vm_b, nv_b, b);
    b += lit.negated ? "!=" : "=";
    canon_term_str(pool, syms, lit.args[0], vm_b, nv_b, b);
    if (a <= b) { var_map = vm_a; next_var = nv_a; return a; }
    else        { var_map = vm_b; next_var = nv_b; return b; }
  }
  if (lit.negated) s = "~";
  s += syms.name(lit.sym);
  if (!lit.args.empty()) {
    s += "(";
    for (size_t i = 0; i < lit.args.size(); i++) {
      if (i > 0) s += ",";
      canon_term_str(pool, syms, lit.args[i], var_map, next_var, s);
    }
    s += ")";
  }
  return s;
}







static std::string clause_canon_str(const Clause &c, const TermPool &pool,
                                     const SymbolTable &syms) {
  
  std::vector<std::string> shapes;
  for (size_t i = 0; i < c.lits.size(); i++) {
    std::map<int, int> dummy_map; int dummy_nv = 0;
    shapes.push_back(canon_lit_str(pool, syms, c.lits[i], dummy_map, dummy_nv));
  }
  

  std::vector<size_t> order(shapes.size());
  for (size_t i = 0; i < order.size(); i++) order[i] = i;
  std::sort(order.begin(), order.end(),
            [&shapes](size_t a, size_t b) { return shapes[a] < shapes[b]; });

  







  std::vector<std::string> final_lits;
  {
    std::map<int, int> var_map;
    int next_var = 0;
    for (size_t k = 0; k < order.size(); k++) {
      final_lits.push_back(
          canon_lit_str(pool, syms, c.lits[order[k]], var_map, next_var));
    }
  }
  std::sort(final_lits.begin(), final_lits.end());
  std::string out;
  for (size_t k = 0; k < final_lits.size(); k++) {
    if (k > 0) out += "|";
    out += final_lits[k];
  }
  return out;
}

static bool clauses_alpha_equal(const Clause &a, const Clause &b,
                                 const TermPool &pool, const SymbolTable &syms) {
  if (a.lits.size() != b.lits.size()) return false;
  return clause_canon_str(a, pool, syms) == clause_canon_str(b, pool, syms);
}

static int verify_rw(const std::vector<Clause> &parents, const Clause &concl,
                     TermPool &pool) {
  if (parents.size() < 2) return -1;

  





  SymbolTable rename_syms;

  
  for (size_t main_idx = 0; main_idx < parents.size() && likely(!deadline_expired()); main_idx++) {
    




    std::vector<std::pair<int, int>> equations;
    for (size_t eq_idx = 0; eq_idx < parents.size(); eq_idx++) {
      if (eq_idx == main_idx) continue;
      const Clause &eq_parent = parents[eq_idx];
      









      if (eq_parent.lits.size() != 1) continue;
      Clause renamed = clause_rename_vars(pool, rename_syms, eq_parent);
      for (size_t li = 0; li < renamed.lits.size(); li++) {
        const Literal &eqlit = renamed.lits[li];
        if (eqlit.sym == EQ_SYM && !eqlit.negated && eqlit.args.size() == 2) {
          equations.push_back({eqlit.args[0], eqlit.args[1]});
          equations.push_back({eqlit.args[1], eqlit.args[0]});
        }
      }
    }
    if (equations.empty()) continue;

    


    const int MAX_STEPS = 4;
    const Clause &main_cl = parents[main_idx];

    

    for (size_t li = 0; li < main_cl.lits.size(); li++) {
      const Literal &orig_lit = main_cl.lits[li];

      
      
      struct WorkItem {
        Literal lit;
        int depth;
      };
      std::vector<WorkItem> worklist;
      worklist.push_back({orig_lit, 0});

      for (size_t wi = 0; wi < worklist.size() && wi < 50 && likely(!deadline_expired()); wi++) {
        
        Literal cur_lit = worklist[wi].lit;
        int depth = worklist[wi].depth;

        
        Clause candidate;
        for (size_t k = 0; k < main_cl.lits.size(); k++) {
          if (k == li) candidate.lits.push_back(cur_lit);
          else candidate.lits.push_back(main_cl.lits[k]);
        }
        if (clause_matches(candidate, concl, pool))
          return 1;

        if (depth >= MAX_STEPS) continue;

        
        for (size_t ei = 0; ei < equations.size(); ei++) {
          int lhs = equations[ei].first;
          int rhs = equations[ei].second;
          for (size_t ai = 0; ai < cur_lit.args.size(); ai++) {
            auto rewrites = apply_one_rewrite(pool, cur_lit.args[ai], lhs, rhs);
            for (size_t ri = 0; ri < rewrites.size(); ri++) {
              Literal new_lit = cur_lit;
              new_lit.args[ai] = rewrites[ri];
              
              worklist.push_back({new_lit, depth + 1});
            }
          }
        }
      }
    }
  }
  return -1;
}














int compute_rw(const std::vector<Clause> &parents,
               TermPool &pool,
               SymbolTable &syms,
               std::vector<std::string> &out,
               int max_candidates) {
  if (parents.size() < 2) return 0;
  std::set<std::string> seen;

  

  for (size_t main_idx = 0; main_idx < parents.size() &&
       (int)out.size() < max_candidates &&
       likely(!deadline_expired()); main_idx++) {
    const Clause &main_cl = parents[main_idx];
    for (size_t unit_idx = 0; unit_idx < parents.size() &&
         (int)out.size() < max_candidates; unit_idx++) {
      if (unit_idx == main_idx) continue;
      if (parents[unit_idx].lits.size() != 1) continue;
      Literal u = parents[unit_idx].lits[0];
      
      for (size_t li = 0; li < main_cl.lits.size() &&
           (int)out.size() < max_candidates; li++) {
        const Literal &ml = main_cl.lits[li];
        
        if (ml.sym != u.sym) continue;
        if (ml.negated == u.negated) continue;
        if (ml.args.size() != u.args.size()) continue;
        Subst sub;
        bool ok = true;
        for (size_t ai = 0; ai < ml.args.size(); ai++) {
          if (!unify(pool, ml.args[ai], u.args[ai], sub)) { ok = false; break; }
        }
        if (!ok) continue;
        
        Clause result;
        for (size_t k = 0; k < main_cl.lits.size(); k++)
          if (k != li)
            result.lits.push_back(apply_subst_lit(pool, main_cl.lits[k], sub));
        std::string s = clause_to_string(result, pool, syms);
        if (seen.insert(s).second)
          out.push_back(s);
      }
    }
  }

  for (size_t main_idx = 0; main_idx < parents.size() &&
       (int)out.size() < max_candidates &&
       likely(!deadline_expired()); main_idx++) {

    



    std::vector<std::pair<int, int> > equations;
    for (size_t eq_idx = 0; eq_idx < parents.size(); eq_idx++) {
      if (eq_idx == main_idx) continue;
      if (parents[eq_idx].lits.size() != 1) continue;
      for (size_t li = 0; li < parents[eq_idx].lits.size(); li++) {
        const Literal &eqlit = parents[eq_idx].lits[li];
        if (eqlit.sym == EQ_SYM && !eqlit.negated && eqlit.args.size() == 2) {
          equations.push_back(std::make_pair(eqlit.args[0], eqlit.args[1]));
          equations.push_back(std::make_pair(eqlit.args[1], eqlit.args[0]));
        }
      }
    }
    if (equations.empty()) continue;

    const int MAX_STEPS = 4;
    const Clause &main_cl = parents[main_idx];

    
    for (size_t li = 0; li < main_cl.lits.size() &&
         (int)out.size() < max_candidates; li++) {
      const Literal &orig_lit = main_cl.lits[li];

      struct WorkItem { Literal lit; int depth; };
      std::vector<WorkItem> worklist;
      WorkItem seed; seed.lit = orig_lit; seed.depth = 0;
      worklist.push_back(seed);

      for (size_t wi = 0; wi < worklist.size() && wi < 50 &&
           (int)out.size() < max_candidates &&
           likely(!deadline_expired()); wi++) {
        Literal cur_lit = worklist[wi].lit;
        int depth = worklist[wi].depth;

        
        Clause candidate;
        for (size_t k = 0; k < main_cl.lits.size(); k++) {
          if (k == li) candidate.lits.push_back(cur_lit);
          else candidate.lits.push_back(main_cl.lits[k]);
        }
        std::string s = clause_to_string(candidate, pool, syms);
        if (seen.insert(s).second)
          out.push_back(s);
        if ((int)out.size() >= max_candidates) break;

        if (depth >= MAX_STEPS) continue;

        for (size_t ei = 0; ei < equations.size(); ei++) {
          int lhs = equations[ei].first;
          int rhs = equations[ei].second;
          for (size_t ai = 0; ai < cur_lit.args.size(); ai++) {
            std::vector<int> rewrites = apply_one_rewrite(pool,
                cur_lit.args[ai], lhs, rhs);
            for (size_t ri = 0; ri < rewrites.size(); ri++) {
              Literal new_lit = cur_lit;
              new_lit.args[ai] = rewrites[ri];
              WorkItem ni; ni.lit = new_lit; ni.depth = depth + 1;
              worklist.push_back(ni);
            }
          }
        }
      }
    }
  }
  return (int)out.size();
}















struct UnifPosResult {
  std::vector<std::vector<int> > positions;
  std::vector<Subst> substs;
};

static void unif_pos_cb(const std::vector<int> &pos, const Subst &sub,
                        void *data) {
  UnifPosResult *r = (UnifPosResult *)data;
  r->positions.push_back(pos);
  r->substs.push_back(sub);
}




static int spm_apply_unify_pair(TermPool &pool,
                                 SymbolTable &syms,
                                 const Clause &main_orig,
                                 const Clause &eq_renamed,
                                 size_t eli,
                                 int dir,
                                 std::set<std::string> &seen,
                                 std::vector<std::string> &out,
                                 int max_candidates) {
  if ((int)out.size() >= max_candidates) return 0;
  const Literal &eq = eq_renamed.lits[eli];
  if (eq.sym != EQ_SYM || eq.negated || eq.args.size() != 2) return 0;
  int lhs = eq.args[dir];
  int rhs = eq.args[1 - dir];

  

  Clause eq_rest;
  for (size_t k = 0; k < eq_renamed.lits.size(); k++)
    if (k != eli) eq_rest.lits.push_back(eq_renamed.lits[k]);

  
  for (size_t li = 0; li < main_orig.lits.size() &&
       (int)out.size() < max_candidates &&
       likely(!deadline_expired()); li++) {
    const Literal &ml = main_orig.lits[li];
    for (size_t ai = 0; ai < ml.args.size() &&
         (int)out.size() < max_candidates; ai++) {
      UnifPosResult r;
      std::vector<int> pos_stack;
      find_unifiable(pool, ml.args[ai], lhs, pos_stack,
                     unif_pos_cb, &r);
      for (size_t mi = 0; mi < r.positions.size() &&
           (int)out.size() < max_candidates; mi++) {
        const Subst &sub = r.substs[mi];
        
        int new_rhs = apply_subst(pool, rhs, sub);
        Clause result;
        for (size_t k = 0; k < main_orig.lits.size(); k++) {
          Literal nl;
          nl.negated = main_orig.lits[k].negated;
          nl.sym = main_orig.lits[k].sym;
          for (size_t aj = 0; aj < main_orig.lits[k].args.size(); aj++) {
            int t = main_orig.lits[k].args[aj];
            if (k == li && aj == ai) {
              t = replace_at(pool, t, r.positions[mi], 0, new_rhs);
            }
            nl.args.push_back(apply_subst(pool, t, sub));
          }
          result.lits.push_back(nl);
        }
        
        for (size_t k = 0; k < eq_rest.lits.size(); k++)
          result.lits.push_back(apply_subst_lit(pool, eq_rest.lits[k], sub));
        std::string s = clause_to_string(result, pool, syms);
        if (seen.insert(s).second)
          out.push_back(s);
      }
    }
  }
  return 0;
}









static int compute_binary_resolution(const std::vector<Clause> &parents,
                                      TermPool &pool,
                                      SymbolTable &syms,
                                      std::set<std::string> &seen,
                                      std::vector<std::string> &out,
                                      int max_candidates) {
  if (parents.size() < 2) return 0;
  int produced = 0;
  for (size_t i = 0; i < parents.size() &&
       (int)out.size() < max_candidates &&
       likely(!deadline_expired()); i++) {
    for (size_t j = 0; j < parents.size() &&
         (int)out.size() < max_candidates &&
         likely(!deadline_expired()); j++) {
      if (i == j) continue;
      const Clause &p_i = parents[i];
      
      Clause p_j = clause_rename_vars(pool, syms, parents[j]);
      for (size_t li = 0; li < p_i.lits.size() &&
           (int)out.size() < max_candidates &&
           likely(!deadline_expired()); li++) {
        const Literal &Li = p_i.lits[li];
        for (size_t lj = 0; lj < p_j.lits.size() &&
             (int)out.size() < max_candidates; lj++) {
          const Literal &Lj = p_j.lits[lj];
          if (Li.sym != Lj.sym) continue;
          if (Li.negated == Lj.negated) continue;
          if (Li.args.size() != Lj.args.size()) continue;
          Subst sub;
          bool ok = true;
          for (size_t a = 0; a < Li.args.size(); a++) {
            if (!unify(pool, Li.args[a], Lj.args[a], sub)) { ok = false; break; }
          }
          if (!ok) continue;
          
          Clause result;
          for (size_t k = 0; k < p_i.lits.size(); k++) {
            if (k == li) continue;
            Literal nl = apply_subst_lit(pool, p_i.lits[k], sub);
            bool dup = false;
            for (size_t r = 0; r < result.lits.size(); r++) {
              if (lits_equal(result.lits[r], nl, pool)) { dup = true; break; }
            }
            if (!dup) result.lits.push_back(nl);
          }
          for (size_t k = 0; k < p_j.lits.size(); k++) {
            if (k == lj) continue;
            Literal nl = apply_subst_lit(pool, p_j.lits[k], sub);
            bool dup = false;
            for (size_t r = 0; r < result.lits.size(); r++) {
              if (lits_equal(result.lits[r], nl, pool)) { dup = true; break; }
            }
            if (!dup) result.lits.push_back(nl);
          }
          std::string s = clause_to_string(result, pool, syms);
          if (seen.insert(s).second) {
            out.push_back(s);
            produced++;
          }
        }
      }
    }
  }
  return produced;
}






static int compute_sr(const std::vector<Clause> &parents,
                      TermPool &pool,
                      SymbolTable &syms,
                      std::set<std::string> &seen,
                      std::vector<std::string> &out,
                      int max_candidates) {
  if (parents.size() < 2) return 0;
  int produced = 0;

  
  for (size_t main_idx = 0; main_idx < parents.size() &&
       (int)out.size() < max_candidates &&
       likely(!deadline_expired()); main_idx++) {
    const Clause &main_cl = parents[main_idx];
    for (size_t li = 0; li < main_cl.lits.size() &&
         (int)out.size() < max_candidates; li++) {
      for (size_t si = 0; si < parents.size() &&
           (int)out.size() < max_candidates; si++) {
        if (si == main_idx) continue;
        const Clause &simp = parents[si];
        if (simp.lits.size() != 1) continue;
        Literal comp = simp.lits[0];
        comp.negated = !comp.negated;
        if (comp.sym != main_cl.lits[li].sym) continue;
        if (comp.negated != main_cl.lits[li].negated) continue;
        if (comp.args.size() != main_cl.lits[li].args.size()) continue;
        Subst sub;
        bool ok = true;
        for (size_t ai = 0; ai < comp.args.size(); ai++) {
          if (!unify(pool, comp.args[ai], main_cl.lits[li].args[ai], sub))
            { ok = false; break; }
        }
        if (!ok) continue;
        Clause result;
        for (size_t k = 0; k < main_cl.lits.size(); k++) {
          if (k == li) continue;
          result.lits.push_back(apply_subst_lit(pool, main_cl.lits[k], sub));
        }
        std::string s = clause_to_string(result, pool, syms);
        if (seen.insert(s).second) {
          out.push_back(s);
          produced++;
        }
      }
    }
  }

  
  for (size_t main_idx = 0; main_idx < parents.size() &&
       (int)out.size() < max_candidates &&
       likely(!deadline_expired()); main_idx++) {
    const Clause &main_cl = parents[main_idx];
    Clause result = main_cl;
    bool any_removed = false;
    for (size_t li = 0; li < result.lits.size() &&
         likely(!deadline_expired()); ) {
      bool removed = false;
      for (size_t si = 0; si < parents.size(); si++) {
        if (si == main_idx) continue;
        const Clause &simp = parents[si];
        if (simp.lits.size() != 1) continue;
        Literal comp = simp.lits[0];
        comp.negated = !comp.negated;
        Subst sub;
        bool match_ok = false;
        if (comp.sym == result.lits[li].sym &&
            comp.negated == result.lits[li].negated &&
            comp.args.size() == result.lits[li].args.size()) {
          match_ok = true;
          for (size_t ai = 0; ai < comp.args.size(); ai++) {
            if (!unify(pool, comp.args[ai], result.lits[li].args[ai], sub))
              { match_ok = false; break; }
          }
        }
        if (match_ok) {
          result.lits.erase(result.lits.begin() + li);
          for (size_t k = 0; k < result.lits.size(); k++)
            result.lits[k] = apply_subst_lit(pool, result.lits[k], sub);
          removed = true;
          any_removed = true;
          break;
        }
      }
      if (!removed) li++;
    }
    if (!any_removed) continue;
    std::string s = clause_to_string(result, pool, syms);
    if (seen.insert(s).second) {
      out.push_back(s);
      produced++;
    }
  }

  return produced;
}




static int compute_er(const Clause &parent,
                       TermPool &pool,
                       SymbolTable &syms,
                       std::set<std::string> &seen,
                       std::vector<std::string> &out,
                       int max_candidates) {
  int produced = 0;
  for (size_t i = 0; i < parent.lits.size() &&
       (int)out.size() < max_candidates &&
       likely(!deadline_expired()); i++) {
    const Literal &lit = parent.lits[i];
    if (lit.sym != EQ_SYM || !lit.negated || lit.args.size() != 2) continue;
    Subst sub;
    if (!unify(pool, lit.args[0], lit.args[1], sub)) continue;
    Clause result = remove_lit(parent, i);
    for (size_t j = 0; j < result.lits.size(); j++)
      result.lits[j] = apply_subst_lit(pool, result.lits[j], sub);
    std::string s = clause_to_string(result, pool, syms);
    if (seen.insert(s).second) {
      out.push_back(s);
      produced++;
    }
  }
  return produced;
}



















int compute_spm(const std::vector<Clause> &parents,
                TermPool &pool,
                SymbolTable &syms,
                std::vector<std::string> &out,
                int max_candidates) {
  if (parents.size() < 2) return 0;
  std::set<std::string> seen;

  
  {
    std::vector<std::string> rw_out;
    compute_rw(parents, pool, syms, rw_out, max_candidates);
    for (size_t i = 0; i < rw_out.size() && (int)out.size() < max_candidates; i++) {
      if (seen.insert(rw_out[i]).second)
        out.push_back(rw_out[i]);
    }
  }

  

  compute_binary_resolution(parents, pool, syms, seen, out, max_candidates);

  
  const int MAX_STEPS = 8;

  for (size_t pidx1 = 0; pidx1 < parents.size() &&
       (int)out.size() < max_candidates &&
       likely(!deadline_expired()); pidx1++) {
    for (size_t pidx2 = 0; pidx2 < parents.size() &&
         (int)out.size() < max_candidates &&
         likely(!deadline_expired()); pidx2++) {
      if (pidx1 == pidx2) continue;
      const Clause &p1 = parents[pidx1];
      const Clause &p2 = parents[pidx2];

      
      for (size_t eli = 0; eli < p2.lits.size() &&
           (int)out.size() < max_candidates &&
           likely(!deadline_expired()); eli++) {
        const Literal &eq = p2.lits[eli];
        if (eq.sym != EQ_SYM || eq.negated || eq.args.size() != 2) continue;

        
        Clause p2_rest;
        for (size_t k = 0; k < p2.lits.size(); k++)
          if (k != eli) p2_rest.lits.push_back(p2.lits[k]);

        
        for (int dir = 0; dir < 2; dir++) {
          int lhs = eq.args[dir];
          int rhs = eq.args[1 - dir];

          struct WorkItem { Clause cl; int depth; };
          std::vector<WorkItem> worklist;
          WorkItem seed; seed.cl = p1; seed.depth = 0;
          worklist.push_back(seed);

          for (size_t wi = 0; wi < worklist.size() && wi < 50 &&
               (int)out.size() < max_candidates &&
               likely(!deadline_expired()); wi++) {
            Clause cur_cl = worklist[wi].cl;
            int depth = worklist[wi].depth;

            
            Clause candidate;
            for (size_t k = 0; k < cur_cl.lits.size(); k++)
              candidate.lits.push_back(cur_cl.lits[k]);
            for (size_t k = 0; k < p2_rest.lits.size(); k++)
              candidate.lits.push_back(p2_rest.lits[k]);

            std::string s = clause_to_string(candidate, pool, syms);
            if (seen.insert(s).second)
              out.push_back(s);
            if ((int)out.size() >= max_candidates) break;

            if (depth >= MAX_STEPS) continue;

            
            for (size_t li = 0; li < cur_cl.lits.size(); li++) {
              for (size_t ai = 0; ai < cur_cl.lits[li].args.size(); ai++) {
                std::vector<int> rewrites = apply_one_rewrite(pool,
                    cur_cl.lits[li].args[ai], lhs, rhs);
                for (size_t ri = 0; ri < rewrites.size(); ri++) {
                  Clause new_cl = cur_cl;
                  new_cl.lits[li].args[ai] = rewrites[ri];
                  WorkItem ni; ni.cl = new_cl; ni.depth = depth + 1;
                  worklist.push_back(ni);
                }
              }
            }
          }
        }
      }
    }
  }

  




  for (size_t pidx1 = 0; pidx1 < parents.size() &&
       (int)out.size() < max_candidates &&
       likely(!deadline_expired()); pidx1++) {
    for (size_t pidx2 = 0; pidx2 < parents.size() &&
         (int)out.size() < max_candidates &&
         likely(!deadline_expired()); pidx2++) {
      if (pidx1 == pidx2) continue;
      const Clause &main_cl = parents[pidx1];
      Clause eq_renamed = clause_rename_vars(pool, syms, parents[pidx2]);
      for (size_t eli = 0; eli < eq_renamed.lits.size() &&
           (int)out.size() < max_candidates &&
           likely(!deadline_expired()); eli++) {
        const Literal &eq = eq_renamed.lits[eli];
        if (eq.sym != EQ_SYM || eq.negated || eq.args.size() != 2) continue;
        for (int dir = 0; dir < 2; dir++) {
          spm_apply_unify_pair(pool, syms, main_cl, eq_renamed,
                                eli, dir, seen, out, max_candidates);
        }
      }
    }
  }
  return (int)out.size();
}






static int verify_spm(const std::vector<Clause> &parents, const Clause &concl,
                      TermPool &pool, const SymbolTable &syms) {
  
  int rc = verify_rw(parents, concl, pool);
  if (rc == 1) return 1;

  





  rc = verify_sr(parents, concl, pool, syms);
  if (rc == 1) return 1;

  


  rc = verify_binary_resolution(parents, concl, pool, syms);
  if (rc == 1) return 1;

  if (parents.size() < 2) return -1;

  





  const int MAX_STEPS = 8;

  for (size_t pidx1 = 0; pidx1 < parents.size() && likely(!deadline_expired()); pidx1++) {
    for (size_t pidx2 = 0; pidx2 < parents.size() && likely(!deadline_expired()); pidx2++) {
      if (pidx1 == pidx2) continue;
      const Clause &p1 = parents[pidx1];
      const Clause &p2 = parents[pidx2];

      
      for (size_t eli = 0; eli < p2.lits.size() && likely(!deadline_expired()); eli++) {
        const Literal &eq = p2.lits[eli];
        if (eq.sym != EQ_SYM || eq.negated || eq.args.size() != 2) continue;

        
        Clause p2_rest;
        for (size_t k = 0; k < p2.lits.size(); k++)
          if (k != eli) p2_rest.lits.push_back(p2.lits[k]);

        
        for (int dir = 0; dir < 2; dir++) {
          int lhs = eq.args[dir];
          int rhs = eq.args[1 - dir];

          




          struct WorkItem {
            Clause cl;
            Clause rest;
            int depth;
          };
          std::vector<WorkItem> worklist;
          worklist.push_back({p1, p2_rest, 0});

          for (size_t wi = 0; wi < worklist.size() && wi < 50 && likely(!deadline_expired()); wi++) {
            Clause cur_cl = worklist[wi].cl;
            Clause cur_rest = worklist[wi].rest;
            int depth = worklist[wi].depth;

            








            Clause candidate;
            for (size_t k = 0; k < cur_cl.lits.size(); k++)
              candidate.lits.push_back(cur_cl.lits[k]);
            for (size_t k = 0; k < cur_rest.lits.size(); k++)
              candidate.lits.push_back(cur_rest.lits[k]);

            if (clause_matches(candidate, concl, pool))
              return 1;

            if (depth >= MAX_STEPS) continue;

            







            for (size_t li = 0; li < cur_cl.lits.size(); li++) {
              for (size_t ai = 0; ai < cur_cl.lits[li].args.size(); ai++) {
                std::vector<RewriteResult> rewrites = apply_one_rewrite_subs(
                    pool, cur_cl.lits[li].args[ai], lhs, rhs);
                for (size_t ri = 0; ri < rewrites.size(); ri++) {
                  


                  Clause new_cl;
                  for (size_t k = 0; k < cur_cl.lits.size(); k++) {
                    Literal nl;
                    nl.negated = cur_cl.lits[k].negated;
                    nl.sym = cur_cl.lits[k].sym;
                    for (size_t aj = 0; aj < cur_cl.lits[k].args.size(); aj++) {
                      int t = cur_cl.lits[k].args[aj];
                      if (k == li && aj == ai) {
                        t = rewrites[ri].term;
                      }
                      nl.args.push_back(apply_subst(pool, t, rewrites[ri].sub));
                    }
                    new_cl.lits.push_back(nl);
                  }
                  




                  Clause sub_rest;
                  for (size_t k = 0; k < cur_rest.lits.size(); k++)
                    sub_rest.lits.push_back(
                        apply_subst_lit(pool, cur_rest.lits[k], rewrites[ri].sub));
                  Clause cand;
                  for (size_t k = 0; k < new_cl.lits.size(); k++)
                    cand.lits.push_back(new_cl.lits[k]);
                  for (size_t k = 0; k < sub_rest.lits.size(); k++)
                    cand.lits.push_back(sub_rest.lits[k]);
                  




                  Clause cand_clean;
                  for (size_t k = 0; k < cand.lits.size(); k++) {
                    if (is_trivially_false(cand.lits[k], pool)) continue;
                    bool dup = false;
                    for (size_t r = 0; r < cand_clean.lits.size(); r++) {
                      if (lits_equal(cand_clean.lits[r], cand.lits[k], pool)) {
                        dup = true; break;
                      }
                    }
                    if (!dup) cand_clean.lits.push_back(cand.lits[k]);
                  }
                  if (clause_matches(cand_clean, concl, pool))
                    return 1;
                  worklist.push_back({new_cl, sub_rest, depth + 1});
                }
              }
            }
          }
        }
      }
    }
  }
  return -1;
}




static int verify_ef(const Clause &parent, const Clause &concl,
                     TermPool &pool) {
  for (size_t i = 0; i < parent.lits.size(); i++) {
    if (parent.lits[i].sym != EQ_SYM || parent.lits[i].negated) continue;
    for (size_t j = i + 1; j < parent.lits.size(); j++) {
      if (parent.lits[j].sym != EQ_SYM || parent.lits[j].negated) continue;
      
      for (int oi = 0; oi < 2; oi++) {
        for (int oj = 0; oj < 2; oj++) {
          Subst sub;
          if (unify(pool, parent.lits[i].args[oi],
                    parent.lits[j].args[oj], sub)) {
            

            Clause candidate;
            for (size_t k = 0; k < parent.lits.size(); k++) {
              if (k == j) continue;
              candidate.lits.push_back(
                  apply_subst_lit(pool, parent.lits[k], sub));
            }
            
            Literal diseq;
            diseq.negated = true;
            diseq.sym = EQ_SYM;
            diseq.args.push_back(
                apply_subst(pool, parent.lits[i].args[1 - oi], sub));
            diseq.args.push_back(
                apply_subst(pool, parent.lits[j].args[1 - oj], sub));
            candidate.lits.push_back(diseq);
            if (clause_matches(candidate, concl, pool))
              return 1;
          }
        }
      }
    }
  }
  return -1;
}










static int verify_split_conjunct(const Clause &parent, const Clause &concl,
                                 const TermPool &pool) {
  if (clause_subset(concl, parent, pool) &&
      clause_subset(parent, concl, pool))
    return 1;
  return -1;
}









static int verify_copy(const Clause &parent, const Clause &concl,
                       const TermPool &pool) {
  if (parent.lits.size() == concl.lits.size()) {
    if (clause_subset(concl, parent, pool) &&
        clause_subset(parent, concl, pool))
      return 1;
    return -1;
  }
  
  return verify_cn(parent, concl, pool);
}





static int verify_factor(const Clause &parent, const Clause &concl,
                         TermPool &pool) {
  if (concl.lits.size() >= parent.lits.size()) return -1;
  
  for (size_t i = 0; i < parent.lits.size() && !deadline_expired(); i++) {
    for (size_t j = i + 1; j < parent.lits.size(); j++) {
      
      if (parent.lits[i].negated != parent.lits[j].negated) continue;
      if (parent.lits[i].sym != parent.lits[j].sym) continue;
      if (parent.lits[i].args.size() != parent.lits[j].args.size()) continue;
      
      Subst sub;
      bool ok = true;
      for (size_t ai = 0; ai < parent.lits[i].args.size(); ai++) {
        if (!unify(pool, parent.lits[i].args[ai],
                   parent.lits[j].args[ai], sub)) {
          ok = false; break;
        }
      }
      if (!ok) continue;
      
      Clause candidate = remove_lit(parent, j);
      for (size_t k = 0; k < candidate.lits.size(); k++)
        candidate.lits[k] = apply_subst_lit(pool, candidate.lits[k], sub);
      if (clause_matches(candidate, concl, pool))
        return 1;
    }
  }
  return -1;
}


















int verify_skolemize_clausify(const Clause &parent, const Clause &concl,
                              const TermPool &pool, const SymbolTable &syms) {
  
  if (parent.lits.empty() && !concl.lits.empty())
    return 0;
  
  for (size_t i = 0; i < concl.lits.size(); i++) {
    const std::string &nm = syms.name(concl.lits[i].sym);
    if ((nm == "$false" && !concl.lits[i].negated) ||
        (nm == "$true" && concl.lits[i].negated))
      continue;  
    if ((nm == "$false" && concl.lits[i].negated) ||
        (nm == "$true" && !concl.lits[i].negated))
      return 0;  
  }
  
  std::map<int, int> parent_preds;  
  for (size_t i = 0; i < parent.lits.size(); i++) {
    int sym = parent.lits[i].sym;
    if (sym == EQ_SYM) sym = -2;  
    if (parent.lits[i].negated)
      parent_preds[sym] |= 2;
    else
      parent_preds[sym] |= 1;
  }
  
  for (size_t i = 0; i < concl.lits.size(); i++) {
    int sym = concl.lits[i].sym;
    if (sym == EQ_SYM) sym = -2;
    

    if (sym != -2 && syms.is_var(sym)) continue;
    const std::string &name = syms.name(sym >= 0 ? sym : 0);
    if (sym >= 0 && (name.compare(0, 3, "esk") == 0 ||
        name.compare(0, 2, "sK") == 0 ||
        name.compare(0, 2, "sF") == 0 ||
        (name.size() >= 2 && (name[0] == 'c' || name[0] == 'f') &&
         name[1] >= '0' && name[1] <= '9')))
      continue;
    auto it = parent_preds.find(sym);
    if (it == parent_preds.end())
      return 0;  
    int parent_pol = it->second;
    int concl_pol = concl.lits[i].negated ? 2 : 1;
    if (!(parent_pol & concl_pol))
      return 0;  
  }
  





  bool parent_is_simple = (parent.lits.size() <= 5);
  if (parent_is_simple && !parent.lits.empty() && !concl.lits.empty()) {
    
    std::map<int, int> concl_preds;
    for (size_t i = 0; i < concl.lits.size(); i++) {
      int sym = concl.lits[i].sym;
      if (sym == EQ_SYM) sym = -2;
      if (concl.lits[i].negated)
        concl_preds[sym] |= 2;
      else
        concl_preds[sym] |= 1;
    }
    
    for (auto it = parent_preds.begin(); it != parent_preds.end(); ++it) {
      int sym = it->first;
      
      if (sym >= 0) {
        const std::string &name = syms.name(sym);
        if (name.compare(0, 3, "esk") == 0 ||
            name.compare(0, 2, "sK") == 0 ||
            name.compare(0, 2, "sF") == 0 ||
            (name.size() >= 2 && (name[0] == 'c' || name[0] == 'f') &&
             name[1] >= '0' && name[1] <= '9'))
          continue;
      }
      if (concl_preds.find(sym) == concl_preds.end())
        return 0;  
    }
  }
  return -1;  
}


