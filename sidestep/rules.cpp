static bool clause_contains(const Clause &cl, const Literal &lit,
                            const TermPool &pool) {
  for (size_t i = 0; i < cl.lits.size(); i++)
    if (lits_equal(cl.lits[i], lit, pool)) return true;
  return false;
}



static bool clause_subset(const Clause &a, const Clause &b,
                          const TermPool &pool) {
  for (size_t i = 0; i < a.lits.size(); i++)
    if (!clause_contains(b, a.lits[i], pool)) return false;
  return true;
}


static Clause remove_lit(const Clause &cl, size_t idx) {
  Clause result;
  for (size_t i = 0; i < cl.lits.size(); i++)
    if (i != idx) result.lits.push_back(cl.lits[i]);
  return result;
}


static bool is_trivially_true(const Literal &lit, const TermPool &pool) {
  if (lit.sym == EQ_SYM && !lit.negated && lit.args.size() == 2)
    return terms_equal(pool, lit.args[0], lit.args[1]);
  return false;
}


static bool is_trivially_false(const Literal &lit, const TermPool &pool) {
  if (lit.sym == EQ_SYM && lit.negated && lit.args.size() == 2)
    return terms_equal(pool, lit.args[0], lit.args[1]);
  return false;
}




static int replace_at(TermPool &pool, int t,
                      const std::vector<int> &position, size_t depth,
                      int replacement) {
  if (depth >= position.size()) return replacement;
  

  Term term = pool.get(t);
  int child_idx = position[depth];
  if (child_idx < 0 || child_idx >= (int)term.args.size()) return t;
  std::vector<int> new_args = term.args;
  new_args[child_idx] = replace_at(pool, term.args[child_idx],
                                    position, depth + 1, replacement);
  return pool.alloc(term.sym, new_args);
}



typedef void (*MatchCallback)(const std::vector<int> &pos, const Subst &sub,
                              void *data);

static void find_matches(const TermPool &pool, int t, int pattern,
                         std::vector<int> &pos_stack,
                         MatchCallback callback, void *data,
                         int depth = 0) {
  if (unlikely(depth > 200 || deadline_expired())) return;
  const Term &term = pool.get(t);
  const Term &pat  = pool.get(pattern);
  





  if (pat.sym < 0 ||
      (pat.sym == term.sym && pat.args.size() == term.args.size())) {
    Subst sub;
    if (match(pool, pattern, t, sub))
      callback(pos_stack, sub, data);
  }
  
  for (size_t i = 0; i < term.args.size(); i++) {
    pos_stack.push_back((int)i);
    find_matches(pool, term.args[i], pattern, pos_stack, callback, data,
                 depth + 1);
    pos_stack.pop_back();
  }
}





static void find_unifiable(const TermPool &pool_const, int t, int pattern,
                           std::vector<int> &pos_stack,
                           MatchCallback callback, void *data,
                           int depth = 0) {
  if (unlikely(depth > 200 || deadline_expired())) return;
  const Term &term = pool_const.get(t);
  const Term &pat  = pool_const.get(pattern);
  


  if (pat.sym < 0 || term.sym < 0 ||
      (pat.sym == term.sym && pat.args.size() == term.args.size())) {
    Subst sub;
    if (unify(pool_const, pattern, t, sub))
      callback(pos_stack, sub, data);
  }
  for (size_t i = 0; i < term.args.size(); i++) {
    pos_stack.push_back((int)i);
    find_unifiable(pool_const, term.args[i], pattern, pos_stack,
                   callback, data, depth + 1);
    pos_stack.pop_back();
  }
}












static int Rename_counter = 0;

static int rename_term(TermPool &pool, SymbolTable &syms, int t,
                       std::map<int, int> &var_remap) {
  

  Term term = pool.get(t);
  if (term.sym < 0) {
    std::map<int, int>::iterator it = var_remap.find(term.sym);
    int new_sym;
    if (it != var_remap.end()) new_sym = it->second;
    else {
      


      char buf[32];
      snprintf(buf, sizeof(buf), "RV%d", ++Rename_counter);
      new_sym = syms.intern_var(buf);
      var_remap[term.sym] = new_sym;
    }
    return pool.alloc(new_sym);
  }
  if (term.args.empty()) return t;  
  std::vector<int> new_args;
  bool changed = false;
  for (size_t i = 0; i < term.args.size(); i++) {
    int na = rename_term(pool, syms, term.args[i], var_remap);
    new_args.push_back(na);
    if (na != term.args[i]) changed = true;
  }
  if (!changed) return t;
  return pool.alloc(term.sym, new_args);
}

static Clause clause_rename_vars(TermPool &pool, SymbolTable &syms,
                                  const Clause &c) {
  std::map<int, int> var_remap;
  Clause out;
  for (size_t i = 0; i < c.lits.size(); i++) {
    Literal nl;
    nl.negated = c.lits[i].negated;
    nl.sym = c.lits[i].sym;
    for (size_t a = 0; a < c.lits[i].args.size(); a++) {
      nl.args.push_back(rename_term(pool, syms,
                                     c.lits[i].args[a], var_remap));
    }
    out.lits.push_back(nl);
  }
  return out;
}









static int verify_cn(const Clause &parent, const Clause &concl,
                     const TermPool &pool) {
  


  if (!clause_subset(concl, parent, pool)) return -1;
  
  for (size_t i = 0; i < parent.lits.size(); i++) {
    if (clause_contains(concl, parent.lits[i], pool)) continue;
    if (is_trivially_false(parent.lits[i], pool)) continue;
    
    bool is_dup = false;
    for (size_t j = 0; j < i; j++)
      if (lits_equal(parent.lits[i], parent.lits[j], pool))
        { is_dup = true; break; }
    if (is_dup) continue;
    return -1;  
  }
  return 1;
}




static int verify_er(const Clause &parent, const Clause &concl,
                     TermPool &pool) {
  

  for (size_t i = 0; i < parent.lits.size(); i++) {
    const Literal &lit = parent.lits[i];
    if (lit.sym != EQ_SYM || !lit.negated || lit.args.size() != 2)
      continue;
    
    Subst sub;
    if (!unify(pool, lit.args[0], lit.args[1], sub)) continue;
    
    Clause resolvent = remove_lit(parent, i);
    for (size_t j = 0; j < resolvent.lits.size(); j++)
      resolvent.lits[j] = apply_subst_lit(pool, resolvent.lits[j], sub);
    
    if (resolvent.lits.size() == concl.lits.size() &&
        clause_subset(concl, resolvent, pool) &&
        clause_subset(resolvent, concl, pool))
      return 1;
  }
  return -1;
}






