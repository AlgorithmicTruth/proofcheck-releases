static bool csr_extend_subsume(const TermPool &pool, const Literal &target,
                                const Clause &main_cl, size_t excluded_idx,
                                Subst &sub_inout) {
  for (size_t i = 0; i < main_cl.lits.size(); i++) {
    if (i == excluded_idx) continue;
    const Literal &ml = main_cl.lits[i];
    if (ml.sym != target.sym) continue;
    if (ml.negated != target.negated) continue;
    if (ml.args.size() != target.args.size()) continue;
    Subst tmp = sub_inout;
    bool ok = true;
    for (size_t a = 0; a < ml.args.size(); a++) {
      if (!unify(pool, target.args[a], ml.args[a], tmp)) { ok = false; break; }
    }
    if (ok) { sub_inout = tmp; return true; }
  }
  return false;
}

static int verify_csr_multi(const std::vector<Clause> &parents,
                             const Clause &concl,
                             TermPool &pool,
                             SymbolTable &syms) {
  if (parents.size() < 2) return -1;
  for (size_t main_idx = 0; main_idx < parents.size() &&
       likely(!deadline_expired()); main_idx++) {
    const Clause &main_cl = parents[main_idx];
    for (size_t simp_idx = 0; simp_idx < parents.size() &&
         likely(!deadline_expired()); simp_idx++) {
      if (simp_idx == main_idx) continue;
      if (parents[simp_idx].lits.size() < 2) continue;  

      
      Clause simp = clause_rename_vars(pool, syms, parents[simp_idx]);

      
      for (size_t li = 0; li < main_cl.lits.size() &&
           likely(!deadline_expired()); li++) {
        const Literal &L = main_cl.lits[li];
        for (size_t di = 0; di < simp.lits.size(); di++) {
          const Literal &Di = simp.lits[di];
          
          if (L.sym != Di.sym) continue;
          if (L.negated == Di.negated) continue;
          if (L.args.size() != Di.args.size()) continue;
          Subst sub;
          bool ok = true;
          for (size_t a = 0; a < L.args.size(); a++) {
            if (!unify(pool, L.args[a], Di.args[a], sub)) { ok = false; break; }
          }
          if (!ok) continue;
          
          bool all_subsumed = true;
          for (size_t dj = 0; dj < simp.lits.size(); dj++) {
            if (dj == di) continue;
            if (!csr_extend_subsume(pool, simp.lits[dj], main_cl, li, sub)) {
              all_subsumed = false;
              break;
            }
          }
          if (!all_subsumed) continue;
          

          Clause result;
          for (size_t k = 0; k < main_cl.lits.size(); k++) {
            if (k == li) continue;
            Literal nl = apply_subst_lit(pool, main_cl.lits[k], sub);
            bool dup = false;
            for (size_t r = 0; r < result.lits.size(); r++) {
              if (lits_equal(result.lits[r], nl, pool)) { dup = true; break; }
            }
            if (!dup) result.lits.push_back(nl);
          }
          if (clause_matches(result, concl, pool) ||
              clauses_alpha_equal(result, concl, pool, syms))
            return 1;
        }
      }
    }
  }
  return -1;
}

int dispatch_rule(const char *rule,
                  const std::vector<Clause> &parents,
                  const Clause &concl,
                  TermPool &pool,
                  SymbolTable &syms) {
  
  if (concl.lits.empty()) {
    
    return verify_sr(parents, concl, pool, syms);
  }

  
  if (parents.size() == 1) {
    if (strcmp(rule, "cn") == 0)
      return verify_cn(parents[0], concl, pool);
    if (strcmp(rule, "er") == 0)
      return verify_er(parents[0], concl, pool);
    if (strcmp(rule, "ef") == 0)
      return verify_ef(parents[0], concl, pool);
    if (strcmp(rule, "split_conjunct") == 0)
      return verify_split_conjunct(parents[0], concl, pool);
    if (strcmp(rule, "copy") == 0)
      return verify_copy(parents[0], concl, pool);
    if (strcmp(rule, "factor") == 0 || strcmp(rule, "factoring") == 0)
      return verify_factor(parents[0], concl, pool);
    if (strcmp(rule, "condense") == 0 || strcmp(rule, "condensation") == 0)
      return verify_condense(parents[0], concl, pool);
    if (strcmp(rule, "instantiate") == 0 || strcmp(rule, "instance") == 0)
      return verify_instantiate(parents[0], concl, pool);
  }

  
  if (strcmp(rule, "rw") == 0 || strcmp(rule, "paramod") == 0 ||
      strcmp(rule, "forward_demodulation") == 0 ||
      strcmp(rule, "backward_demodulation") == 0 ||
      strcmp(rule, "demodulation") == 0) {
    int rc = verify_rw(parents, concl, pool);
    if (rc == 1) return 1;
    


    return verify_spm(parents, concl, pool, syms);
  }
  if (strcmp(rule, "spm") == 0 || strcmp(rule, "superposition") == 0)
    return verify_spm(parents, concl, pool, syms);
  if (strcmp(rule, "sr") == 0 || strcmp(rule, "csr") == 0 ||
      strcmp(rule, "resolve") == 0 || strcmp(rule, "xxres") == 0 ||
      strcmp(rule, "resolution") == 0 ||
      strcmp(rule, "unit_resulting_resolution") == 0 ||
      strcmp(rule, "subsumption_resolution") == 0) {
    int rc = verify_sr(parents, concl, pool, syms);
    if (rc == 1) return 1;
    
    rc = verify_csr_multi(parents, concl, pool, syms);
    if (rc == 1) return 1;
    
    return verify_binary_resolution(parents, concl, pool, syms);
  }
  if (strcmp(rule, "consequence") == 0 || strcmp(rule, "horn") == 0 ||
      strcmp(rule, "deduction") == 0)
    return verify_consequence(parents, concl, pool, syms);
  if (strcmp(rule, "global_subsumption") == 0)
    return verify_global_subsumption(parents, concl, pool);
  if (strcmp(rule, "instantiate") == 0)
    return verify_instantiate(parents[0], concl, pool);

  


  if (unlikely(deadline_expired())) return -1;
  int rc = verify_rw(parents, concl, pool);
  if (rc == 1) return 1;

  return -1;  
}




int dispatch_compute(const char *rule,
                     const std::vector<Clause> &parents,
                     TermPool &pool,
                     SymbolTable &syms,
                     std::vector<std::string> &out,
                     int max_candidates) {
  if (strcmp(rule, "rw") == 0 || strcmp(rule, "paramod") == 0 ||
      strcmp(rule, "forward_demodulation") == 0 ||
      strcmp(rule, "backward_demodulation") == 0 ||
      strcmp(rule, "demodulation") == 0)
    return compute_rw(parents, pool, syms, out, max_candidates);
  if (strcmp(rule, "spm") == 0 || strcmp(rule, "superposition") == 0)
    return compute_spm(parents, pool, syms, out, max_candidates);
  if (strcmp(rule, "sr") == 0 || strcmp(rule, "csr") == 0 ||
      strcmp(rule, "resolve") == 0 || strcmp(rule, "xxres") == 0 ||
      strcmp(rule, "resolution") == 0 ||
      strcmp(rule, "unit_resulting_resolution") == 0 ||
      strcmp(rule, "subsumption_resolution") == 0) {
    

    std::set<std::string> seen;
    compute_sr(parents, pool, syms, seen, out, max_candidates);
    compute_binary_resolution(parents, pool, syms, seen, out, max_candidates);
    return (int)out.size();
  }
  if (strcmp(rule, "er") == 0) {
    if (parents.size() != 1) return -1;
    std::set<std::string> seen;
    compute_er(parents[0], pool, syms, seen, out, max_candidates);
    return (int)out.size();
  }
  return -1;
}

