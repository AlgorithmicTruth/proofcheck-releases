static bool canon_equiv(const char *a, const char *b) {
  NodePool pool;
  Node *na = FormulaParser(a, strlen(a), pool).parse();
  Node *nb = FormulaParser(b, strlen(b), pool).parse();
  if (!na || !nb) return false;
  Node *ca = fof_canonicalize(na, pool);
  Node *cb = fof_canonicalize(nb, pool);
  return node_to_string(ca) == node_to_string(cb);
}

static void test_fof_canonicalize(void) {
  TEST("fof_canon: variable_rename");
  ASSERT(canon_equiv("![A,B] : p(A,B)", "![X,Y] : p(X,Y)"),
         "alpha-equivalent formulas should match");
  PASS();

  TEST("fof_canon: fof_nnf (implication)");
  ASSERT(canon_equiv("p(a) => q(a)", "~p(a) | q(a)"),
         "A=>B should canonicalize same as ~A|B");
  PASS();

  TEST("fof_canon: fof_nnf (negated implication)");
  ASSERT(canon_equiv("~(p(a) => q(a))", "p(a) & ~q(a)"),
         "~(A=>B) should canonicalize same as A & ~B");
  PASS();

  TEST("fof_canon: fof_nnf (biconditional)");
  ASSERT(canon_equiv("p(a) <=> q(a)",
                     "(~p(a) | q(a)) & (~q(a) | p(a))"),
         "A<=>B should expand to NNF");
  PASS();

  TEST("fof_canon: distribute");
  ASSERT(canon_equiv("~p | (q & r)", "(~p | q) & (~p | r)"),
         "distribution should canonicalize identically");
  PASS();

  TEST("fof_canon: distribute (large)");
  ASSERT(canon_equiv(
    "~x | (a & b & c & d)",
    "(~x | a) & (~x | b) & (~x | c) & (~x | d)"),
         "distribution over 4 conjuncts");
  PASS();

  TEST("fof_canon: shift_quantors");
  ASSERT(canon_equiv("![X] : (p(X) & q(X))",
                     "(![X] : p(X)) & (![X] : q(X))"),
         "miniscoping should match shifted quantifiers");
  PASS();

  TEST("fof_canon: shift_quantors (vacuous)");
  ASSERT(canon_equiv("![X] : (p(X) & q(a))",
                     "(![X] : p(X)) & q(a)"),
         "vacuous quantifier stripped after miniscoping");
  PASS();

  TEST("fof_canon: fof_simplification ($false)");
  ASSERT(canon_equiv("p(a) | $false", "p(a)"),
         "$false in disjunction should be eliminated");
  PASS();

  TEST("fof_canon: fof_simplification ($true)");
  ASSERT(canon_equiv("p(a) & $true", "p(a)"),
         "$true in conjunction should be eliminated");
  PASS();

  TEST("fof_canon: compound (nnf + distribute)");
  ASSERT(canon_equiv("~(p | q) | (r & s)",
                     "(~p | r) & (~p | s) & (~q | r) & (~q | s)"),
         "NNF + distribution compound");
  PASS();

  TEST("fof_canon: double negation");
  ASSERT(canon_equiv("~~p(a)", "p(a)"),
         "double negation eliminated");
  PASS();

  TEST("fof_canon: De Morgan");
  ASSERT(canon_equiv("~(p(a) & q(a))", "~p(a) | ~q(a)"),
         "De Morgan pushes negation");
  PASS();

  TEST("fof_canon: evil non-equivalent (forall vs exists)");
  ASSERT(!canon_equiv("![X] : p(X)", "?[X] : p(X)"),
         "forall and exists must NOT match");
  PASS();

  TEST("fof_canon: evil non-equivalent (different predicates)");
  ASSERT(!canon_equiv("p(a)", "q(a)"),
         "different predicates must NOT match");
  PASS();

  TEST("fof_canon: evil non-equivalent (swapped args)");
  ASSERT(!canon_equiv("![X,Y] : p(X,Y)", "![X,Y] : p(Y,X)"),
         "swapped arguments must NOT match");
  PASS();
}

