static void test_guard_predicate_stripping(void) {
  TEST("guard strip: universal antecedent (real DAT060_1 ax_19 shape)");
  {
    const char *guarded =
      "![N:$int,D:$i,Ar:$i,M:$int] : "
      "((lamp_sort_data(D) & lamp_sort_array(Ar)) => "
      "(M != N => p(Ar,N,D) = p(Ar,M)))";
    const char *real =
      "![N:$int,D:$i,Ar:$i,M:$int] : "
      "(M != N => p(Ar,N,D) = p(Ar,M))";
    std::string a = strip_and_canon(guarded);
    std::string b = canon_of(real);
    ASSERT(!a.empty() && !b.empty() && a == b,
           "a legitimately guarded universal must canonicalize identically "
           "to its real (unguarded) source after stripping");
  }
  PASS();

  TEST("guard strip: existential conjunct");
  {
    const char *guarded = "?[D:$i] : (lamp_sort_data(D) & q(D))";
    const char *real    = "?[D:$i] : q(D)";
    std::string a = strip_and_canon(guarded);
    std::string b = canon_of(real);
    ASSERT(!a.empty() && !b.empty() && a == b,
           "an existential guard conjunct must strip cleanly");
  }
  PASS();

  TEST("guard strip: no guard present is a no-op");
  {
    const char *plain = "![X:$i] : p(X)";
    std::string a = strip_and_canon(plain);
    std::string b = canon_of(plain);
    ASSERT(!a.empty() && a == b, "unguarded formulas must be unaffected");
  }
  PASS();

  TEST("guard strip: negative control -- guard on a non-$i (already-typed) "
       "variable must NOT strip");
  {
    


    const char *fake = "![N:$int] : (lamp_sort_data(N) => p(N))";
    const char *real = "![N:$int] : p(N)";
    std::string a = strip_and_canon(fake);
    std::string b = canon_of(real);
    ASSERT(!a.empty() && !b.empty() && a != b,
           "a guard atom on a non-$i variable must not be stripped -- "
           "no partial credit");
  }
  PASS();

  TEST("guard strip: negative control -- wrong arity guard atom");
  {
    const char *fake = "![D:$i] : ((lamp_sort_data(D,D)) => p(D))";
    const char *real = "![D:$i] : p(D)";
    std::string a = strip_and_canon(fake);
    std::string b = canon_of(real);
    ASSERT(!a.empty() && !b.empty() && a != b,
           "a 2-arity 'guard' atom is not a guard at all and must not strip");
  }
  PASS();

  TEST("guard strip: negative control -- guard disjoined, not IMPL-antecedent");
  {
    const char *fake = "![D:$i] : (lamp_sort_data(D) | p(D))";
    const char *real = "![D:$i] : p(D)";
    std::string a = strip_and_canon(fake);
    std::string b = canon_of(real);
    ASSERT(!a.empty() && !b.empty() && a != b,
           "a disjoined guard is the wrong shape and must not strip");
  }
  PASS();

  TEST("guard strip: negative control -- smuggled content survives the guard "
       "wrapper (strip normalizes the wrapper, never launders a real change)");
  {
    


    const char *smuggled =
      "![D:$i] : (lamp_sort_data(D) => (p(D) & extra(D)))";
    const char *real = "![D:$i] : p(D)";
    std::string a = strip_and_canon(smuggled);
    std::string b = canon_of(real);
    ASSERT(!a.empty() && !b.empty() && a != b,
           "a smuggled stronger body must still mismatch after guard-stripping");
  }
  PASS();

  TEST("guard strip: negative control -- same variable guarded twice");
  {
    const char *fake =
      "![D:$i] : ((lamp_sort_data(D) & lamp_sort_array(D)) => p(D))";
    std::string a = strip_and_canon(fake);
    std::string b = canon_of("![D:$i] : p(D)");
    ASSERT(!a.empty() && !b.empty() && a != b,
           "guarding the same variable twice is not a legitimate erasure "
           "shape and must not strip");
  }
  PASS();
}






