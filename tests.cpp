static void test_structural_cycle(void) {
  TEST("structural: cycle detection");
  auto clauses = parse_tstp_proof(std::string(EVIL_CIRCULAR));
  
  std::map<std::string, int> state;
  bool has_cycle = false;
  for (auto &pair : clauses) state[pair.first] = 0;
  struct DfsFrame { std::string name; size_t pidx; };
  for (auto &pair : clauses) {
    if (state[pair.first] != 0 || has_cycle) continue;
    std::vector<DfsFrame> stk;
    DfsFrame f0; f0.name = pair.first; f0.pidx = 0;
    stk.push_back(f0); state[pair.first] = 1;
    while (!stk.empty() && !has_cycle) {
      DfsFrame &top = stk.back();
      auto si = clauses.find(top.name);
      if (si == clauses.end() || top.pidx >= si->second.parents.size()) {
        state[top.name] = 2; stk.pop_back(); continue;
      }
      std::string pname = si->second.parents[top.pidx]; top.pidx++;
      if (!state.count(pname)) continue;
      if (state[pname] == 1) has_cycle = true;
      else if (state[pname] == 0) {
        state[pname] = 1;
        DfsFrame fn; fn.name = pname; fn.pidx = 0;
        stk.push_back(fn);
      }
    }
  }
  ASSERT(has_cycle, "should detect cycle in s2<->s3");
  PASS();

  TEST("structural: no cycle in valid proof");
  auto valid = parse_tstp_proof(std::string(VALID_PROOF_1));
  state.clear(); has_cycle = false;
  for (auto &pair : valid) state[pair.first] = 0;
  for (auto &pair : valid) {
    if (state[pair.first] != 0 || has_cycle) continue;
    std::vector<DfsFrame> stk;
    DfsFrame f0; f0.name = pair.first; f0.pidx = 0;
    stk.push_back(f0); state[pair.first] = 1;
    while (!stk.empty() && !has_cycle) {
      DfsFrame &top = stk.back();
      auto si = valid.find(top.name);
      if (si == valid.end() || top.pidx >= si->second.parents.size()) {
        state[top.name] = 2; stk.pop_back(); continue;
      }
      std::string pname = si->second.parents[top.pidx]; top.pidx++;
      if (!state.count(pname)) continue;
      if (state[pname] == 1) has_cycle = true;
      else if (state[pname] == 0) {
        state[pname] = 1;
        DfsFrame fn; fn.name = pname; fn.pidx = 0;
        stk.push_back(fn);
      }
    }
  }
  ASSERT(!has_cycle, "valid proof should be acyclic");
  PASS();
}

