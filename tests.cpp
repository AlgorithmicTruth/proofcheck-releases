static void test_clausify_smuggle(void) {
  


  TEST("clausify: smuggled disjunct drop detected");
  {
    auto clauses = parse_tstp_proof(std::string(EVIL_CLAUSIFY_SMUGGLE));
    



    const ProofStep &cstep = clauses.at("evil");
    const ProofStep &parent = clauses.at("ax1");
    NodePool cpool;
    Node *par = FormulaParser(parent.body.c_str(), parent.body.size(),
                               cpool).parse();
    Node *stp = FormulaParser(cstep.body.c_str(), cstep.body.size(),
                               cpool).parse();
    ASSERT(par && stp, "parse both formulas");
    Node *canon_par = fof_canonicalize(par, cpool);
    Node *canon_stp = fof_canonicalize(stp, cpool);
    ASSERT(canon_par && canon_stp, "canonicalize both");
    
    std::string step_str = node_to_string(canon_stp);
    bool found = false;
    std::vector<const Node *> wk;
    wk.push_back(canon_par);
    while (!wk.empty()) {
      const Node *cn = wk.back(); wk.pop_back();
      if (!cn) continue;
      if (cn->kind == NK_AND) {
        for (size_t ci = 0; ci < cn->children.size(); ci++)
          wk.push_back(cn->children[ci]);
      } else {
        if (node_to_string(cn) == step_str) found = true;
      }
    }
    ASSERT(!found, "p(a) should NOT match any conjunct of p(a)|p(b)");
  }
  PASS();

  TEST("clausify: valid clausification accepted");
  {
    auto clauses = parse_tstp_proof(std::string(VALID_CLAUSIFY));
    const ProofStep &cstep = clauses.at("cl1");
    const ProofStep &parent = clauses.at("ax1");
    NodePool cpool;
    Node *par = FormulaParser(parent.body.c_str(), parent.body.size(),
                               cpool).parse();
    Node *stp = FormulaParser(cstep.body.c_str(), cstep.body.size(),
                               cpool).parse();
    ASSERT(par && stp, "parse both formulas");
    Node *canon_par = fof_canonicalize(par, cpool);
    Node *canon_stp = fof_canonicalize(stp, cpool);
    ASSERT(canon_par && canon_stp, "canonicalize both");
    std::string step_str = node_to_string(canon_stp);
    bool found = false;
    std::vector<const Node *> wk;
    wk.push_back(canon_par);
    while (!wk.empty()) {
      const Node *cn = wk.back(); wk.pop_back();
      if (!cn) continue;
      if (cn->kind == NK_AND) {
        for (size_t ci = 0; ci < cn->children.size(); ci++)
          wk.push_back(cn->children[ci]);
      } else {
        if (node_to_string(cn) == step_str) found = true;
      }
    }
    ASSERT(found, "p(a)|p(b) should match conjunct of p(a)|p(b)");
  }
  PASS();
}

