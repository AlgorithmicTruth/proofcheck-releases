static void test_axiom_consistency(void) {
  TEST("axiom consistency: $false as axiom");
  const char *evil = "fof(a1, axiom, $false, file('t',a1)).\n"
                     "fof(c, conjecture, p(a), file('t',c)).\n"
                     "fof(s1, negated_conjecture, ~p(a),\n"
                     "    inference(negated_conjecture, [status(cth)], [c])).\n"
                     "fof(f1, plain, $false,\n"
                     "    inference(consequence, [status(thm)], [s1, a1])).\n";
  auto clauses = parse_tstp_proof(std::string(evil));
  bool found_false_axiom = false;
  for (auto &pair : clauses) {
    if (!pair.second.is_input) continue;
    if (pair.second.role == "conjecture" ||
        pair.second.role == "negated_conjecture") continue;
    std::string b = normalize_ws(pair.second.body);
    if (b == "$false" || b == "false") found_false_axiom = true;
  }
  ASSERT(found_false_axiom, "should detect $false axiom");
  PASS();

  TEST("axiom consistency: t != t pattern");
  const char *evil2 = "fof(a1, axiom, e0 != e0, file('t',a1)).\n"
                      "fof(c, conjecture, p(a), file('t',c)).\n"
                      "fof(s1, negated_conjecture, ~p(a),\n"
                      "    inference(negated_conjecture, [status(cth)], [c])).\n"
                      "fof(f1, plain, $false,\n"
                      "    inference(consequence, [status(thm)], [s1, a1])).\n";
  auto cl2 = parse_tstp_proof(std::string(evil2));
  bool found_self_neq = false;
  for (auto &pair : cl2) {
    if (!pair.second.is_input) continue;
    if (pair.second.role == "conjecture" ||
        pair.second.role == "negated_conjecture") continue;
    std::string b = normalize_ws(pair.second.body);
    size_t neq = b.find("!=");
    if (neq != std::string::npos) {
      std::string lhs = b.substr(0, neq);
      std::string rhs = b.substr(neq + 2);
      if (lhs == rhs) found_self_neq = true;
    }
  }
  ASSERT(found_self_neq, "should detect e0 != e0");
  PASS();
}





